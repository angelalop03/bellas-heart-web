package com.us.TFG.db;

/**
 * Conexión a la base de datos. Imita la parte de java.sql.Connection que usa el juego para que
 * el mismo código funcione en escritorio (JDBC) y en navegador (SQLite compilado a WebAssembly).
 */
public interface Connection extends AutoCloseable {
    PreparedStatement prepareStatement(String sql) throws SQLException;

    PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException;

    Statement createStatement() throws SQLException;

    void setAutoCommit(boolean autoCommit) throws SQLException;

    boolean getAutoCommit() throws SQLException;

    void commit() throws SQLException;

    void rollback() throws SQLException;

    boolean isClosed() throws SQLException;

    @Override
    void close() throws SQLException;
}
