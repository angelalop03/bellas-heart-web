package com.us.TFG.db.jdbc;

import com.us.TFG.db.Connection;
import com.us.TFG.db.PreparedStatement;
import com.us.TFG.db.SQLException;
import com.us.TFG.db.Statement;

/** Implementación de escritorio y tests: delega en el driver JDBC de SQLite (org.xerial). */
public class JdbcConnection implements Connection {
    private final java.sql.Connection delegate;

    public JdbcConnection(java.sql.Connection delegate) {
        this.delegate = delegate;
    }

    public static JdbcConnection open(String url) throws SQLException {
        return new JdbcConnection(call(() -> java.sql.DriverManager.getConnection(url)));
    }

    interface SqlCall<T> {
        T call() throws java.sql.SQLException;
    }

    interface SqlRun {
        void run() throws java.sql.SQLException;
    }

    static <T> T call(SqlCall<T> call) throws SQLException {
        try {
            return call.call();
        } catch (java.sql.SQLException e) {
            throw new SQLException(e.getMessage(), e);
        }
    }

    static void run(SqlRun run) throws SQLException {
        try {
            run.run();
        } catch (java.sql.SQLException e) {
            throw new SQLException(e.getMessage(), e);
        }
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        return new JdbcPreparedStatement(call(() -> delegate.prepareStatement(sql)));
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        int keys = autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS
            ? java.sql.Statement.RETURN_GENERATED_KEYS
            : java.sql.Statement.NO_GENERATED_KEYS;
        return new JdbcPreparedStatement(call(() -> delegate.prepareStatement(sql, keys)));
    }

    @Override
    public Statement createStatement() throws SQLException {
        return new JdbcStatement(call(delegate::createStatement));
    }

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException {
        run(() -> delegate.setAutoCommit(autoCommit));
    }

    @Override
    public boolean getAutoCommit() throws SQLException {
        return call(delegate::getAutoCommit);
    }

    @Override
    public void commit() throws SQLException {
        run(delegate::commit);
    }

    @Override
    public void rollback() throws SQLException {
        run(delegate::rollback);
    }

    @Override
    public boolean isClosed() throws SQLException {
        return call(delegate::isClosed);
    }

    @Override
    public void close() throws SQLException {
        run(delegate::close);
    }
}
