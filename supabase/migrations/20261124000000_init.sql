-- Contenido: todo el mundo lee; solo admin escribe
create policy "historias publicadas" on public.histories for select using (published or public.is_admin());
create policy "admin historias" on public.histories for all using (public.is_admin()) with check (public.is_admin());

create policy "leer capitulos" on public.chapters for select using (true);
create policy "admin capitulos" on public.chapters for all using (public.is_admin()) with check (public.is_admin());
create policy "leer personajes" on public.characters for select using (true);
create policy "admin personajes" on public.characters for all using (public.is_admin()) with check (public.is_admin());
create policy "leer escenas" on public.scenes for select using (true);
create policy "admin escenas" on public.scenes for all using (public.is_admin()) with check (public.is_admin());
create policy "leer decisiones" on public.decisions for select using (true);
create policy "admin decisiones" on public.decisions for all using (public.is_admin()) with check (public.is_admin());
create policy "leer opciones" on public.options for select using (true);
create policy "admin opciones" on public.options for all using (public.is_admin()) with check (public.is_admin());
create policy "leer noticias" on public.news for select using (true);
create policy "admin noticias" on public.news for all using (public.is_admin()) with check (public.is_admin());

-- Perfiles: cada jugadora ve y edita el suyo; admin ve todos
create policy "ver perfil" on public.profiles for select using (id = auth.uid() or public.is_admin());
create policy "editar perfil" on public.profiles for update using (id = auth.uid()) with check (id = auth.uid());
-- El rol no se puede cambiar desde la app: solo estas columnas son editables
revoke update on public.profiles from anon, authenticated;
grant update (username, first_name, last_name, avatar) on public.profiles to authenticated;

-- Partidas: lectura propia (o admin); escritura solo mediante las funciones; se pueden borrar
create policy "ver partidas" on public.games for select using (user_id = auth.uid() or public.is_admin());
create policy "borrar partidas" on public.games for delete using (user_id = auth.uid());
create policy "ver capitulos de partida" on public.game_chapters for select
  using (exists (select 1 from public.games g where g.id = game_id and (g.user_id = auth.uid() or public.is_admin())));
create policy "ver elecciones" on public.game_choices for select
  using (exists (select 1 from public.games g where g.id = game_id and (g.user_id = auth.uid() or public.is_admin())));

revoke insert, update on public.games, public.game_chapters, public.game_choices from anon, authenticated;

-- Permisos de las funciones
revoke execute on function public.create_game(bigint, text), public.choose_option(bigint, bigint),
  public.delete_my_account(), public.admin_delete_user(uuid) from public, anon;
grant execute on function public.create_game(bigint, text), public.choose_option(bigint, bigint),
  public.delete_my_account(), public.admin_delete_user(uuid) to authenticated;
grant execute on function public.get_story(bigint), public.username_available(text) to anon, authenticated;
