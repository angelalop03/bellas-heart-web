-- =====================================================================
-- Bella's Heart · esquema de base de datos (Supabase / PostgreSQL)
--
-- Contenido de la historia (lectura pública, escritura solo admin):
--   histories, chapters, characters, scenes, decisions, options, news
-- Datos de cada jugador (protegidos con RLS):
--   profiles, games, game_chapters, game_choices
-- La lógica de la partida vive en funciones SQL (create_game, choose_option)
-- para que el progreso sea siempre coherente y nadie edite sus puntos a mano.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Contenido
-- ---------------------------------------------------------------------
create table public.histories (
  id          bigint generated by default as identity primary key,
  title       text    not null,
  description text    not null default '',
  image_path  text    not null default 'Default_History.png',
  published   boolean not null default false,
  created_at  timestamptz not null default now()
);

create table public.chapters (
  id                          bigint generated by default as identity primary key,
  history_id                  bigint references public.histories (id) on delete cascade, -- null = tutorial
  name                        text not null,
  chapter_number              text not null,  -- "0" intro, "1".."5", "6.1".."9.4" ramas
  image_path                  text,
  required_relationship_state text check (required_relationship_state in
                                ('CONFIDENT', 'LOW_TENSION', 'HIGH_TENSION', 'CRITICAL'))
);
create index on public.chapters (history_id);

create table public.characters (
  id         bigint generated by default as identity primary key,
  name       text not null,
  image_path text
);

create table public.scenes (
  id               bigint generated by default as identity primary key,
  chapter_id       bigint not null references public.chapters (id) on delete cascade,
  background_image text,
  scene_order      integer not null
);
create index on public.scenes (chapter_id, scene_order);

create table public.decisions (
  id             bigint generated by default as identity primary key,
  scene_id       bigint not null references public.scenes (id) on delete cascade,
  decision_order integer not null,
  character_id   bigint references public.characters (id) on delete set null,
  dialogue       text not null default ''
);
create index on public.decisions (scene_id, decision_order);

create table public.options (
  id                           bigint generated by default as identity primary key,
  decision_id                  bigint not null references public.decisions (id) on delete cascade,
  text                         text not null,
  points_m                     integer not null default 0, -- malestar psicológico de Bella
  points_r                     integer not null default 0, -- tensión en la relación
  next_decision_id             bigint references public.decisions (id) on delete set null,
  required_psychological_state text -- solo se muestra si Bella está en ese estado
);
create index on public.options (decision_id);

create table public.news (
  id         bigint generated by default as identity primary key,
  title      text not null,
  body       text not null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Jugadores
-- ---------------------------------------------------------------------
create table public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  username   text not null unique check (char_length(username) between 3 and 30),
  first_name text not null default '',
  last_name  text not null default '',
  avatar     text not null default 'default_image',
  role       text not null default 'player' check (role in ('player', 'admin')),
  created_at timestamptz not null default now()
);

create table public.games (
  id                  bigint generated by default as identity primary key,
  user_id             uuid not null references public.profiles (id) on delete cascade,
  history_id          bigint not null references public.histories (id) on delete cascade,
  name                text not null check (char_length(name) between 1 and 40),
  current_chapter_id  bigint references public.chapters (id) on delete set null,
  current_scene_id    bigint references public.scenes (id) on delete set null,
  current_decision_id bigint references public.decisions (id) on delete set null,
  points_m            integer not null default 0,
  points_r            integer not null default 0,
  state               text not null default 'IN_PROGRESS' check (state in ('IN_PROGRESS', 'FINISHED')),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  unique (user_id, name)
);
create index on public.games (user_id);

create table public.game_chapters (
  game_id     bigint not null references public.games (id) on delete cascade,
  chapter_id  bigint not null references public.chapters (id) on delete cascade,
  unlocked_at timestamptz not null default now(),
  played_at   timestamptz,
  primary key (game_id, chapter_id)
);

create table public.game_choices (
  id          bigint generated by default as identity primary key,
  game_id     bigint not null references public.games (id) on delete cascade,
  chapter_id  bigint references public.chapters (id) on delete set null,
  decision_id bigint references public.decisions (id) on delete set null,
  option_id   bigint references public.options (id) on delete set null,
  points_m    integer not null default 0,
  points_r    integer not null default 0,
  created_at  timestamptz not null default now()
);
create index on public.game_choices (game_id, id);

-- ---------------------------------------------------------------------
-- Funciones auxiliares
-- ---------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Mismos umbrales que el juego original (los puntos negativos cuentan como 0).
create or replace function public.psychological_state(p_points integer)
returns text language sql immutable set search_path = ''
as $$
  select case
    when greatest(p_points, 0) < 25 then 'STABLE'
    when p_points < 50 then 'SLIGHTLY_ANXIOUS'
    when p_points < 75 then 'ANXIOUS'
    else 'DISTRESSED' end;
$$;

create or replace function public.relationship_state(p_points integer)
returns text language sql immutable set search_path = ''
as $$
  select case
    when greatest(p_points, 0) < 30 then 'CONFIDENT'
    when p_points < 60 then 'LOW_TENSION'
    when p_points < 80 then 'HIGH_TENSION'
    else 'CRITICAL' end;
$$;

-- "6.2" -> 6.2 ; textos no numéricos al final
create or replace function public.chapter_sort_key(p_number text)
returns numeric language sql immutable set search_path = ''
as $$
  select case when p_number ~ '^\d+(\.\d+)?$' then p_number::numeric else 999999 end;
$$;

-- Crea el perfil al registrarse (datos enviados en options.data del signUp)
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username, first_name, last_name)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'), ''), 'jugadora_' || left(new.id::text, 8)),
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', '')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.username_available(p_username text)
returns boolean language sql stable security definer set search_path = ''
as $$
  select not exists (select 1 from public.profiles where lower(username) = lower(trim(p_username)));
$$;

-- ---------------------------------------------------------------------
-- Lógica de la partida
-- ---------------------------------------------------------------------

-- Primera decisión de una escena / primera escena de un capítulo
create or replace function public.first_decision_of_scene(p_scene_id bigint)
returns bigint language sql stable set search_path = ''
as $$
  select id from public.decisions where scene_id = p_scene_id order by decision_order, id limit 1;
$$;

create or replace function public.first_scene_of_chapter(p_chapter_id bigint)
returns bigint language sql stable set search_path = ''
as $$
  select id from public.scenes where chapter_id = p_chapter_id order by scene_order, id limit 1;
$$;

create or replace function public.create_game(p_history_id bigint, p_name text)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_name text := trim(p_name);
  v_chapter bigint;
  v_scene bigint;
  v_game bigint;
begin
  if v_uid is null then raise exception 'Necesitas iniciar sesión'; end if;
  if v_name = '' then raise exception 'Ponle un nombre a la partida'; end if;
  if not exists (select 1 from public.histories where id = p_history_id and (published or public.is_admin())) then
    raise exception 'Esa historia no está disponible';
  end if;
  if exists (select 1 from public.games where user_id = v_uid and lower(name) = lower(v_name)) then
    raise exception 'Ya tienes una partida con ese nombre';
  end if;

  -- El primer capítulo es la introducción ("0")
  select id into v_chapter from public.chapters
   where history_id = p_history_id
   order by public.chapter_sort_key(chapter_number), id limit 1;
  if v_chapter is null then raise exception 'La historia no tiene capítulos'; end if;
  v_scene := public.first_scene_of_chapter(v_chapter);

  insert into public.games (user_id, history_id, name, current_chapter_id, current_scene_id, current_decision_id)
  values (v_uid, p_history_id, v_name, v_chapter, v_scene, public.first_decision_of_scene(v_scene))
  returning id into v_game;

  insert into public.game_chapters (game_id, chapter_id) values (v_game, v_chapter);
  return v_game;
end;
$$;

-- Elige una opción de la decisión actual y avanza la partida.
-- Devuelve { event: 'decision' | 'scene' | 'chapter_end', game: {...}, next_chapter_id, finished }
create or replace function public.choose_option(p_game_id bigint, p_option_id bigint)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  g public.games;
  o public.options;
  v_scene public.scenes;
  v_next_scene public.scenes;
  v_current_number text;
  v_current_group text;
  v_rel text;
  v_cand record;
  v_next_chapter bigint;
  v_event text;
begin
  select * into g from public.games where id = p_game_id for update;
  if g.id is null or g.user_id <> auth.uid() then raise exception 'Partida no encontrada'; end if;
  if g.state <> 'IN_PROGRESS' then raise exception 'Esta partida ya ha terminado'; end if;

  select * into o from public.options where id = p_option_id;
  if o.id is null or o.decision_id is distinct from g.current_decision_id then
    raise exception 'Esa opción no corresponde a este momento de la historia';
  end if;
  if o.required_psychological_state is not null
     and o.required_psychological_state <> public.psychological_state(g.points_m) then
    raise exception 'Esa opción no está disponible ahora';
  end if;

  g.points_m := g.points_m + o.points_m;
  g.points_r := g.points_r + o.points_r;

  insert into public.game_choices (game_id, chapter_id, decision_id, option_id, points_m, points_r)
  values (g.id, g.current_chapter_id, o.decision_id, o.id, o.points_m, o.points_r);

  if o.next_decision_id is not null then
    -- Igual que el juego original: el fondo (escena) no cambia al saltar de decisión.
    g.current_decision_id := o.next_decision_id;
    v_event := 'decision';
  else
    select * into v_scene from public.scenes where id = g.current_scene_id;
    select * into v_next_scene from public.scenes
     where chapter_id = g.current_chapter_id and scene_order = v_scene.scene_order + 1
     order by id limit 1;

    if v_next_scene.id is not null then
      g.current_scene_id := v_next_scene.id;
      g.current_decision_id := public.first_decision_of_scene(v_next_scene.id);
      v_event := 'scene';
    else
      -- Fin de capítulo: se marca jugado y se desbloquea el siguiente según la relación
      v_event := 'chapter_end';
      update public.game_chapters set played_at = now()
       where game_id = g.id and chapter_id = g.current_chapter_id;

      select chapter_number into v_current_number from public.chapters where id = g.current_chapter_id;
      v_current_group := split_part(v_current_number, '.', 1);
      v_rel := public.relationship_state(g.points_r);

      for v_cand in
        select id, chapter_number, required_relationship_state from public.chapters
         where history_id = g.history_id
           and public.chapter_sort_key(chapter_number) > public.chapter_sort_key(v_current_number)
         order by public.chapter_sort_key(chapter_number), id
      loop
        continue when split_part(v_cand.chapter_number, '.', 1) = v_current_group;
        if v_cand.required_relationship_state is null or v_cand.required_relationship_state = v_rel then
          v_next_chapter := v_cand.id;
          exit;
        end if;
      end loop;

      if v_next_chapter is not null then
        insert into public.game_chapters (game_id, chapter_id) values (g.id, v_next_chapter)
          on conflict do nothing;
        g.current_chapter_id := v_next_chapter;
        g.current_scene_id := public.first_scene_of_chapter(v_next_chapter);
        g.current_decision_id := public.first_decision_of_scene(g.current_scene_id);
      else
        g.state := 'FINISHED';
        g.current_decision_id := null;
      end if;
    end if;
  end if;

  update public.games set
    points_m = g.points_m, points_r = g.points_r,
    current_chapter_id = g.current_chapter_id, current_scene_id = g.current_scene_id,
    current_decision_id = g.current_decision_id, state = g.state, updated_at = now()
  where id = g.id;

  return jsonb_build_object(
    'event', v_event,
    'next_chapter_id', v_next_chapter,
    'finished', g.state = 'FINISHED',
    'game', to_jsonb(g)
  );
end;
$$;

-- Todo el contenido de una historia en una sola llamada (null = tutorial)
create or replace function public.get_story(p_history_id bigint)
returns jsonb language sql stable set search_path = ''
as $$
  with ch as (select * from public.chapters where history_id is not distinct from p_history_id),
       sc as (select s.* from public.scenes s join ch on ch.id = s.chapter_id),
       de as (select d.* from public.decisions d join sc on sc.id = d.scene_id),
       op as (select o.* from public.options o join de on de.id = o.decision_id)
  select jsonb_build_object(
    'chapters',   coalesce((select jsonb_agg(to_jsonb(ch) order by public.chapter_sort_key(ch.chapter_number), ch.id) from ch), '[]'),
    'scenes',     coalesce((select jsonb_agg(to_jsonb(sc) order by sc.chapter_id, sc.scene_order) from sc), '[]'),
    'decisions',  coalesce((select jsonb_agg(to_jsonb(de) order by de.scene_id, de.decision_order) from de), '[]'),
    'options',    coalesce((select jsonb_agg(to_jsonb(op) order by op.decision_id, op.id) from op), '[]'),
    'characters', coalesce((select jsonb_agg(to_jsonb(c) order by c.id) from public.characters c), '[]')
  );
$$;

-- Borrar la propia cuenta (perfil, partidas y elecciones caen en cascada)
create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if auth.uid() is null then raise exception 'Necesitas iniciar sesión'; end if;
  delete from auth.users where id = auth.uid();
end;
$$;

create or replace function public.admin_delete_user(p_user_id uuid)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Solo administradores'; end if;
  if p_user_id = auth.uid() then raise exception 'No puedes borrar tu propia cuenta desde aquí'; end if;
  delete from auth.users where id = p_user_id;
end;
$$;

