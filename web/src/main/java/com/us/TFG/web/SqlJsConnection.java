package com.us.TFG.web;

import com.badlogic.gdx.utils.JsonReader;
import com.badlogic.gdx.utils.JsonValue;
import com.us.TFG.db.Connection;
import com.us.TFG.db.PreparedStatement;
import com.us.TFG.db.ResultSet;
import com.us.TFG.db.SQLException;
import com.us.TFG.db.Statement;

/**
 * Conexión a SQLite (sql.js) con la misma semántica de transacciones que JDBC: con autoCommit desactivado,
 * la transacción se abre al ejecutar la primera sentencia y termina con commit()/rollback(); el juego
 * puede seguir en modo manual después de un commit().
 */
class SqlJsConnection implements Connection {
    private boolean autoCommit = true;
    private boolean transactionOpen;
    private boolean closed;

    /** Lee la respuesta JSON del puente y lanza SQLException si sql.js devolvió un error. */
    static JsonValue parse(String json) throws SQLException {
        JsonValue value = new JsonReader().parse(json);
        if (value.has("error")) {
            throw new SQLException(value.getString("error"));
        }
        return value;
    }

    /** Llamado antes de cada sentencia: en modo manual abre la transacción si aún no lo está. */
    void beforeStatement() throws SQLException {
        if (!autoCommit && !transactionOpen) {
            parse(SqlJsBridge.begin());
            transactionOpen = true;
        }
    }

    @Override
    public PreparedStatement prepareStatement(String sql) {
        return new SqlJsPreparedStatement(this, sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) {
        return new SqlJsPreparedStatement(this, sql);
    }

    @Override
    public Statement createStatement() {
        return new SqlJsPreparedStatement(this, null);
    }

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException {
        if (autoCommit && transactionOpen) {
            // Igual que JDBC: volver a autocommit confirma la transacción en curso.
            commit();
        }
        this.autoCommit = autoCommit;
    }

    @Override
    public boolean getAutoCommit() {
        return autoCommit;
    }

    @Override
    public void commit() throws SQLException {
        if (transactionOpen) {
            transactionOpen = false;
            parse(SqlJsBridge.commit());
        }
    }

    @Override
    public void rollback() throws SQLException {
        if (transactionOpen) {
            transactionOpen = false;
            parse(SqlJsBridge.rollback());
        }
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void close() {
        closed = true;
    }

    static ResultSet singleValue(String column, long value) {
        return new SqlJsResultSet(new JsonReader().parse(
            "{\"columns\":[\"" + column + "\"],\"values\":[[" + value + "]]}"));
    }
}
